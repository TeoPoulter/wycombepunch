import { readFileSync, writeFileSync } from 'node:fs';
const html = readFileSync(new URL('../emails/enquiry-confirmation.html', import.meta.url), 'utf8');
const source = readFileSync(new URL('../emails/enquiry-confirmation.txt', import.meta.url), 'utf8');
const [subjectLine, ...lines] = source.split('\n');
const receipt = { subject: subjectLine.replace(/^Subject:\s*/, ''), html, text: lines.join('\n').trim() };
writeFileSync(new URL('./receipt-template.mjs', import.meta.url), '// Generated by sync-template.mjs from the approved fixed email. No visitor content is interpolated.\nexport const receiptTemplate = ' + JSON.stringify(receipt, null, 2) + ';\n');
